def normalize_company(raw_name: str):
    if not raw_name:
        return "Unknown", "", "Tier 5: Regional Employer", "Not Listed"
    upper = raw_name.upper().strip()
    for key, info in COMPANY_REGISTRY.items():
        if key in upper:
            sub = raw_name.strip() if raw_name.strip().upper() != info["canonical"].upper() else ""
            return info["canonical"], sub, info["tier"], info["est_base"]
    clean = re.sub(r"\b(LLC|Inc\.?|Corp\.?|Corporation|Industries|Company)\b", "", raw_name, flags=re.IGNORECASE).strip(" ,.")
    return clean or raw_name, "", "Tier 5: Regional Employer", "Not Listed"

